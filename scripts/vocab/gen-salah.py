#!/usr/bin/env python3
"""Generate src/utils/generated/salah-words.ts (the "The words in my salah" learning goal).

  python3 scripts/vocab/gen-salah.py --corpus <corpus dir> --words <current.json> [--out <file.ts>]

Same inputs as gen-pages.py (see README.md): the corpus folder holding build/idx.pkl and a JSON dump of
the site's word list. Kept separate from gen-pages.py on purpose: quran-index.ts only carries the surahs
that have a /surah page (Juz Amma), while this goal also needs Al-Fatiha (surah 1).

For each surah in SALAH_SURAHS, the output lists site words in reading order (the first time each one is
read), using the same lemma matching as gen-pages.py:
  * a single site word matches a corpus token when the token's stem lemma is the word's lemma (the corpus
    lemma at the word's `location`); one canonical site word per lemma;
  * a multi-word phrase (e.g. bismillah) matches only at its own `location`, so it appears where it is read.
Words that are not in the Quran verbatim are not matched. Re-run after the word list changes.
"""
import argparse, json, os, pickle, re

# Surahs recited in (nearly) every prayer: Al-Fatiha, and Al-Ikhlas as the most common short surah.
SALAH_SURAHS = [1, 112]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--corpus', default=os.environ.get('QV_CORPUS'))
    ap.add_argument('--words', default=os.environ.get('QV_WORDS'))
    repo = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
    ap.add_argument('--out', default=os.path.join(repo, 'src', 'utils', 'generated', 'salah-words.ts'))
    a = ap.parse_args()
    if not a.corpus or not a.words:
        ap.error('--corpus and --words (or $QV_CORPUS / $QV_WORDS) are required')

    I = pickle.load(open(os.path.join(a.corpus, 'build', 'idx.pkl'), 'rb'))
    W, lem_count = I['W'], I['lem_count']
    words = json.load(open(a.words))['words']

    def is_phrase(w):
        return ' ' in w['arabic'].strip() or w.get('partOfSpeech') == 'phrase'

    word_lemma = {}
    phrase_at = {}  # (surah, ayah, position) -> phrase word id
    for w in words:
        loc = w.get('location')
        if not loc:
            continue
        key = (loc['surah'], loc['ayah'], loc['position'])
        if is_phrase(w):
            phrase_at.setdefault(key, w['id'])
            continue
        d = W[key]
        match = [L for L in d['lems'] if lem_count[L] == w.get('frequency')]
        lem = match[0] if match else d['lem']
        if lem:
            word_lemma[w['id']] = lem

    # Same canonical choice as gen-pages.py.
    def rank(w):
        return (lem_count[word_lemma[w['id']]] != w.get('frequency'), bool(re.fullmatch(r'\d+', w['id'])))
    canonical = {}
    for w in sorted((w for w in words if w['id'] in word_lemma), key=rank):
        canonical.setdefault(word_lemma[w['id']], w['id'])

    out_rows = {}
    for s in SALAH_SURAHS:
        seen, ids = set(), []
        for key in sorted(k for k in W if k[0] == s):
            for wid in (phrase_at.get(key), canonical.get(W[key]['lem'])):
                if wid and wid not in seen:
                    seen.add(wid)
                    ids.append(wid)
        out_rows[s] = ids

    js = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
    out = [
        '// GENERATED by scripts/vocab/gen-salah.py from the Quranic Arabic Corpus. Do not edit by hand.',
        '/* eslint-disable */',
        '',
        '/** Site word ids in reading order (first occurrence) for the surahs recited in salah. */',
        'export const SALAH_SURAH_WORDS: Record<number, string[]> = ' + js({str(k): v for k, v in out_rows.items()}) + ';',
        '',
    ]
    with open(a.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print(' '.join(f'surah {s}: {len(v)} words' for s, v in out_rows.items()), '->', a.out)


if __name__ == '__main__':
    main()
